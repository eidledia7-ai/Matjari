function canUse(feature) {
  const plan = (state.role === 'employee' && state.ownerPlan) 
    ? state.ownerPlan 
    : ((state.subscription && state.subscription.plan) || 'trial');
  
  const cleanPlan = String(plan || 'trial').toLowerCase().trim();
  if (!PLAN_LIMITS[cleanPlan]) {
    console.warn('canUse: unknown plan', cleanPlan);
    return false;
  }
  return PLAN_LIMITS[cleanPlan][feature] === true;
}

function checkLimit(type, currentCount) {
  const plan = (state.role === 'employee' && state.ownerPlan) 
    ? state.ownerPlan 
    : ((state.subscription && state.subscription.plan) || 'trial');
  const cleanPlan = String(plan || 'trial').toLowerCase().trim();
  const max = (PLAN_LIMITS[cleanPlan] && PLAN_LIMITS[cleanPlan][type]) || 0;
  return { allowed: currentCount < max, current: currentCount, max: max };
}

